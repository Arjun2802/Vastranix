@router.post("/push")
def process_sync_batch(
    data: SyncBatchRequest,
    ctx: TenantContext = Depends(get_tenant_context),
    db: Session = Depends(get_db)
):
    processed = []
    failed = []

    for op in data.operations:
        # Check idempotency in AuditLog
        existing = db.query(AuditLog).filter(
            AuditLog.business_id == ctx.business.id,
            AuditLog.entity_id == op.operation_id
        ).first()

        if existing:
            processed.append({"operation_id": op.operation_id, "status": "ALREADY_APPLIED"})
            continue

        try:
            # Record applied sync operation
            log = AuditLog(
                business_id=ctx.business.id,
                user_id=ctx.user.id,
                action=f"OFFLINE_SYNC_{op.action}_{op.entity}",
                entity_type=op.entity,
                entity_id=op.operation_id,
                details=str(op.payload)
            )
            db.add(log)
            db.commit()
            processed.append({"operation_id": op.operation_id, "status": "SUCCESS"})
        except Exception as e:
            failed.append({"operation_id": op.operation_id, "error": str(e)})

    return {
        "client_id": data.client_id,
        "processed_count": len(processed),
        "failed_count": len(failed),
        "results": processed,
        "errors": failed
    }
